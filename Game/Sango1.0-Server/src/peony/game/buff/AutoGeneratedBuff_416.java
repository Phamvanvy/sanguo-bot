package peony.game.buff;

import java.util.*;
import peony.game.*;
import peony.game.buff.*;
import peony.game.skill.*;
import peony.util.*;
import com.pip.util.*;
import org.apache.mina.common.ByteBuffer;
import peony.game.itemenhance.ItemEnhance;

public class AutoGeneratedBuff_416 implements Buff, PropertyEnhancer, Updatable {
    private static final int[] WEAPON = {
        
    };
    public int buffover_addbuff = 0;
    public int buffover_addbuff_level = 0;
    public static int[] DURATION = {
        0, 300000
    };
    public static int[] CHANGE_PHYSICAL_AP_VALUE = {
        0, 200
    };
    public static float[] CHANGE_PHYSICAL_AP_PERCENT = {
        0.0f, 0.0f
    };
    public static int[] CHANGE_MAGIC_AP_VALUE = {
        0, 150
    };
    public static float[] CHANGE_MAGIC_AP_PERCENT = {
        0.0f, 0.0f
    };
    int instanceID;
    int realWeight;
    int level;
    int endTime;
    int multiple;
    int remainSeconds;
    int tickInterval;
    int remainCure;
    int remainDamage;
    int remainMPCure;
    int remainMPDamage;
    int remainAbsorb;
    int effectTimes;
    GameObjectRef owner;
    GameObjectRef source;
    int change_physical_ap_value;
    float change_physical_ap_percent;
    int change_magic_ap_value;
    float change_magic_ap_percent;

    public AutoGeneratedBuff_416(int lvl, Unit src, Unit tgt, int dmg) {
        if (src != null) {
            source = src.ref();
        }
        if (tgt != null) {
            owner = tgt.ref();
        }
        instanceID = BuffUtil.getNextID();
        level = lvl;
        endTime = Time.currTime + BuffUtil.enhanceParam(src, tgt, 416, "buffTime", DURATION[level]);
        multiple = 1;
        change_physical_ap_value = CHANGE_PHYSICAL_AP_VALUE[level];
        change_physical_ap_value = BuffUtil.enhanceParam(src, tgt, 416, "change_physical_ap_value", change_physical_ap_value);
        change_physical_ap_percent = CHANGE_PHYSICAL_AP_PERCENT[level];
        change_physical_ap_percent = BuffUtil.enhanceParam(src, tgt, 416, "change_physical_ap_percent", change_physical_ap_percent);
        change_magic_ap_value = CHANGE_MAGIC_AP_VALUE[level];
        change_magic_ap_value = BuffUtil.enhanceParam(src, tgt, 416, "change_magic_ap_value", change_magic_ap_value);
        change_magic_ap_percent = CHANGE_MAGIC_AP_PERCENT[level];
        change_magic_ap_percent = BuffUtil.enhanceParam(src, tgt, 416, "change_magic_ap_percent", change_magic_ap_percent);
    }

    public int getId() {
        return 416;
    }

    public int getInstanceID() {
        return instanceID;
    }

    public String getName() {
        return "以父之名";
    }

    public String getDesc() {
        return java.text.MessageFormat.format("物理攻击提高{0}点，法术攻击提高{1}点。", CommonUtil.formatValue(change_physical_ap_value * multiple), CommonUtil.formatValue(change_magic_ap_value * multiple));
    }

    private boolean checkWeapon(Unit unit) {
        return true;
    }

    public int getEndTime() {
        return endTime;
    }

    public boolean isGood() {
        return true;
    }

    public boolean dispelable() {
        return false;
    }

    public boolean keepOnDie() {
        return true;
    }

    public int getIconID() {
        return 42 | (multiple << 24);
    }

    public boolean isAreaBuff() {
        return false;
    }

    public int getMergeStrategy() {
        return 1;
    }

    public boolean isNeedMerge() {
        return true;
    }

    public float getchange_dembuff_rate() {
         return 0;
    }

    public boolean merge(Buff buff) {
        if (buff instanceof AutoGeneratedBuff_416) {
            AutoGeneratedBuff_416 other = (AutoGeneratedBuff_416)buff;
            if (level < other.level) {
                level = other.level;
                endTime = other.endTime;
                multiple = 1;
                remainSeconds = other.remainSeconds;
                tickInterval = other.tickInterval;
                remainCure = other.remainCure;
                remainDamage = other.remainDamage;
                remainMPCure = other.remainMPCure;
                remainMPDamage = other.remainMPDamage;
                remainAbsorb = other.remainAbsorb;
                effectTimes = 0;
                owner = other.owner;
                source = other.source;
                change_physical_ap_value = other.change_physical_ap_value;
                change_physical_ap_percent = other.change_physical_ap_percent;
                change_magic_ap_value = other.change_magic_ap_value;
                change_magic_ap_percent = other.change_magic_ap_percent;
            } else if (level == other.level) {
                endTime = other.endTime;
                if (multiple < 3) {
                    multiple++;
                }
            }
            return true;
        }
        return false;
    }

    public GameObjectRef getSource() {
        return source;
    }

    public void setOwner(GameObjectRef o) {
        owner = o;
        if (source == null) {
            source = owner;
        }
    }

    public void resetParams(Unit owner) {
    }

    public boolean update(int diff) {
        if (endTime <= Time.currTime) {
            return true;
        }
        return false;
    }

    public void load(byte[] bytes) {
        ByteBuffer buf = ByteBuffer.wrap(bytes);
        owner = new GameObjectRef(buf.get(), buf.getInt(), buf.getInt());
        source = new GameObjectRef(buf.get(), buf.getInt(), buf.getInt());
        level = buf.getInt();
        endTime = Time.elapseTime(buf.getLong());
        multiple = buf.getInt();
        change_physical_ap_value = CHANGE_PHYSICAL_AP_VALUE[level];
        change_physical_ap_percent = CHANGE_PHYSICAL_AP_PERCENT[level];
        change_magic_ap_value = CHANGE_MAGIC_AP_VALUE[level];
        change_magic_ap_percent = CHANGE_MAGIC_AP_PERCENT[level];
        remainSeconds = buf.getInt();
        tickInterval = buf.getInt();
        remainCure = buf.getInt();
        remainDamage = buf.getInt();
        remainMPCure = buf.getInt();
        remainMPDamage = buf.getInt();
        remainAbsorb = buf.getInt();
        effectTimes = buf.getInt();
    }

    public byte[] save() {
        ByteBuffer buf = ByteBuffer.allocate(66, false);
        buf.put(owner.type);
        buf.putInt(owner.id);
        buf.putInt(owner.instanceId);
        buf.put(source.type);
        buf.putInt(source.id);
        buf.putInt(source.instanceId);
        buf.putInt(level);
        buf.putLong(Time.currentTimeMillis(endTime));
        buf.putInt(multiple);
        buf.putInt(remainSeconds);
        buf.putInt(tickInterval);
        buf.putInt(remainCure);
        buf.putInt(remainDamage);
        buf.putInt(remainMPCure);
        buf.putInt(remainMPDamage);
        buf.putInt(remainAbsorb);
        buf.putInt(effectTimes);
        return buf.array();
    }

    public boolean update2(int time) {
        endTime += time;
        if (endTime <= Time.currTime) {
            return false;
        }
        return true;
    }

    public void enhance(PropertyCalculator pc) {
        if (!checkWeapon(pc.unit)) {
            return;
        }
        pc.attackpowerup += multiple * change_physical_ap_value;
        pc.attackpowerdown += multiple * change_physical_ap_value;
        pc.attackpowerRate += multiple * change_physical_ap_percent / 100.0f;
        pc.spellpowerRate += multiple * change_magic_ap_percent / 100.0f;
        pc.spellpower += multiple * change_magic_ap_value;
    }

}
