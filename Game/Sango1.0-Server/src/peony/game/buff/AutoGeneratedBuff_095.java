package peony.game.buff;

import java.util.*;
import peony.game.*;
import peony.game.buff.*;
import peony.game.skill.*;
import peony.util.*;
import com.pip.util.*;
import org.apache.mina.common.ByteBuffer;
import peony.game.itemenhance.ItemEnhance;

public class AutoGeneratedBuff_095 implements Buff, SkillBuff, CombatEffect {
    private static final int[] WEAPON = {
        
    };
    public int buffover_addbuff = 0;
    public int buffover_addbuff_level = 0;
    public static int[] DURATION = {
        0, -1, -1, -1, -1, -1
    };
    public static String[] LIMIT_SKILLS = {
        "", "63", "63", "63", "63", "63"
    };
    public static int[] CHANGE_CURE_VALUE = {
        0, 0, 0, 0, 0, 0
    };
    public static float[] CHANGE_CURE_PERCENT = {
        0.0f, 15.0f, 18.0f, 21.0f, 24.0f, 27.0f
    };
    Skill skill;
    int instanceID;
    int realWeight;
    int level;
    int endTime;
    int multiple;
    int remainSeconds;
    int tickInterval;
    int remainCure;
    int remainDamage;
    int remainMPCure;
    int remainMPDamage;
    int remainAbsorb;
    int effectTimes;
    GameObjectRef owner;
    GameObjectRef source;
    IntHashSet limitSkills = new IntHashSet();
    String limit_skills;
    int change_cure_value;
    float change_cure_percent;

    public AutoGeneratedBuff_095(Skill skl, int lvl) {
        int dmg = 0;
        skill = skl;
        instanceID = BuffUtil.getNextID();
        level = lvl;
        multiple = 1;
        limit_skills = LIMIT_SKILLS[level];
        change_cure_value = CHANGE_CURE_VALUE[level];
        change_cure_percent = CHANGE_CURE_PERCENT[level];
        String[] secs = limit_skills.split(",");
        for (String s : secs) {
            limitSkills.add(Integer.parseInt(s));
        }
    }

    public int getId() {
        return skill.getId();
    }

    public int getInstanceID() {
        return instanceID;
    }

    public String getName() {
        return "镇心";
    }

    public String getDesc() {
        return java.text.MessageFormat.format("提升镇心理气治疗量{0}", CommonUtil.formatPercent(change_cure_percent * multiple));
    }

    public Skill getSkill() {
        return skill;
    }

    private boolean checkWeapon(Unit unit) {
        return true;
    }

    public int getEndTime() {
        return -1;
    }

    public boolean isGood() {
        return true;
    }

    public boolean dispelable() {
        return false;
    }

    public boolean keepOnDie() {
        return false;
    }

    public int getIconID() {
        return -1;
    }

    public boolean isAreaBuff() {
        return false;
    }

    public int getMergeStrategy() {
        return 2;
    }

    public boolean isNeedMerge() {
        return true;
    }

    public float getchange_dembuff_rate() {
         return 0;
    }

    public boolean merge(Buff buff) {
        if (buff instanceof AutoGeneratedBuff_095) {
            AutoGeneratedBuff_095 other = (AutoGeneratedBuff_095)buff;
            if (level <= other.level) {
                level = other.level;
                endTime = other.endTime;
                multiple = 1;
                remainSeconds = other.remainSeconds;
                tickInterval = other.tickInterval;
                remainCure = other.remainCure;
                remainDamage = other.remainDamage;
                remainMPCure = other.remainMPCure;
                remainMPDamage = other.remainMPDamage;
                remainAbsorb = other.remainAbsorb;
                effectTimes = 0;
                owner = other.owner;
                source = other.source;
                limit_skills = other.limit_skills;
                change_cure_value = other.change_cure_value;
                change_cure_percent = other.change_cure_percent;
            }
            return true;
        }
        return false;
    }

    public GameObjectRef getSource() {
        return source;
    }

    public void setOwner(GameObjectRef o) {
        owner = o;
        if (source == null) {
            source = owner;
        }
    }

    public void resetParams(Unit owner) {
        change_cure_value = CHANGE_CURE_VALUE[level];
        change_cure_value = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 95, "change_cure_value", change_cure_value);
        change_cure_percent = CHANGE_CURE_PERCENT[level];
        change_cure_percent = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 95, "change_cure_percent", change_cure_percent);
    }

    public void preHit(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
        if (!limitSkills.contains(context.skill.getGroupId())) {
            return;
        }
    }

    public void postHit(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
        if (!limitSkills.contains(context.skill.getGroupId())) {
            return;
        }
    }

    public void preDamage(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
        if (!limitSkills.contains(context.skill.getGroupId())) {
            return;
        }
    }

    public void postDamage(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
        if (!limitSkills.contains(context.skill.getGroupId())) {
            return;
        }
        if (isActive && context.damageType == CombatContext.DAMAGE_HEAL && !context.isAdditive) {
            context.damage += context.damage * multiple * change_cure_percent / 100.0f;
            context.damage += multiple * change_cure_value;
            effectTimes++;
        }
    }

    public void finished(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
        if (!limitSkills.contains(context.skill.getGroupId())) {
            return;
        }
    }

}
