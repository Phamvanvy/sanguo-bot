    public AutoGeneratedBuff_051(int lvl, Unit src, Unit tgt, int dmg) {
        if (src != null) {
            source = src.ref();
        }
        if (tgt != null) {
            owner = tgt.ref();
        }
        instanceID = BuffUtil.getNextID();
        level = lvl;
        endTime = Time.currTime + BuffUtil.enhanceParam(src, tgt, 51, "buffTime", DURATION[level]);
        multiple = 1;
        dumb_rate = DUMB_RATE[level];
        dumb_rate = BuffUtil.enhanceParam(src, tgt, 51, "dumb_rate", dumb_rate);
        dumb_rate_var = DUMB_RATE_VAR[level];
        dumb_time = DUMB_TIME[level];
        dumb_time = BuffUtil.enhanceParam(src, tgt, 51, "dumb_time", dumb_time);
        max_effect_times = MAX_EFFECT_TIMES[level];
        max_effect_times = BuffUtil.enhanceParam(src, tgt, 51, "max_effect_times", max_effect_times);
    }

