public class AutoGeneratedBuff_525 implements Buff, CombatEffect {
    private static final int[] WEAPON = {
        
    };
    public int buffover_addbuff = 0;
    public int buffover_addbuff_level = 0;
    public static int[] DURATION = {
        0, -1
    };
    public static float[] ADD_BUFF_RATE = {
        0.0f, 4.0f
    };
    public static String[] ADD_BUFF_RATE_VAR = {
        "", ""
    };
    public static int[] ADD_BUFF_ID = {
        0, 533
    };
    public static int[] ADD_BUFF_LEVEL = {
        0, 1
    };
    int instanceID;
    int realWeight;
    int level;
    int endTime;
    int multiple;
    int remainSeconds;
    int tickInterval;
    int remainCure;
    int remainDamage;
    int remainMPCure;
    int remainMPDamage;
    int remainAbsorb;
    int effectTimes;
    GameObjectRef owner;
    GameObjectRef source;
    float add_buff_rate;
    String add_buff_rate_var;
    int add_buff_id;
    int add_buff_level;


    public AutoGeneratedBuff_525(int lvl) {
        int dmg = 0;
        instanceID = BuffUtil.getNextID();
        level = lvl;
        multiple = 1;
        add_buff_rate = ADD_BUFF_RATE[level];
        add_buff_rate_var = ADD_BUFF_RATE_VAR[level];
        add_buff_id = ADD_BUFF_ID[level];
        add_buff_level = ADD_BUFF_LEVEL[level];
    }

    public int getId() {
        return 525;
    }

    public int getInstanceID() {
        return instanceID;
    }

    public String getName() {
        return "永结同心";
    }

    public String getDesc() {
        return "命中一定几率获得永结同心效果。增加100物攻，80法攻，同时恢复500生命";
    }

    private boolean checkWeapon(Unit unit) {
        return true;
    }

    public int getEndTime() {
        return -1;
    }

    public boolean isGood() {
        return true;
    }

    public boolean dispelable() {
        return false;
    }

    public boolean keepOnDie() {
        return false;
    }

    public int getIconID() {
        return -1;
    }

    public boolean isAreaBuff() {
        return false;
    }

    public int getMergeStrategy() {
        return 4;
    }

    public boolean isNeedMerge() {
        return true;
    }

    public float getchange_dembuff_rate() {
         return 0;
    }

    public boolean merge(Buff buff) {
        if (buff instanceof AutoGeneratedBuff_525) {
            AutoGeneratedBuff_525 other = (AutoGeneratedBuff_525)buff;
            level = other.level;
            endTime = other.endTime;
            multiple = 1;
            remainSeconds = other.remainSeconds;
            tickInterval = other.tickInterval;
            remainCure = other.remainCure;
            remainDamage = other.remainDamage;
            remainMPCure = other.remainMPCure;
            remainMPDamage = other.remainMPDamage;
            remainAbsorb = other.remainAbsorb;
            effectTimes = 0;
            owner = other.owner;
            source = other.source;
            add_buff_rate = other.add_buff_rate;
            add_buff_rate_var = other.add_buff_rate_var;
            add_buff_id = other.add_buff_id;
            add_buff_level = other.add_buff_level;
            return true;
        }
        return false;
    }

    public GameObjectRef getSource() {
        return source;
    }

    public void setOwner(GameObjectRef o) {
        owner = o;
        if (source == null) {
            source = owner;
        }
    }

    public void resetParams(Unit owner) {
        add_buff_rate = ADD_BUFF_RATE[level];
        add_buff_rate = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 525, "add_buff_rate", add_buff_rate);
        add_buff_level = ADD_BUFF_LEVEL[level];
        add_buff_level = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 525, "add_buff_level", add_buff_level);
    }

    public void preHit(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
    }

    public void postHit(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
    }

    public void preDamage(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
    }

    public void postDamage(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
    }

    public void finished(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
        if (isActive && context.hited() && context.isAttack()) {
            boolean hit = false;
            if (add_buff_rate_var.length() == 0) {
                hit = CommonUtil.hit(RND, (int)(multiple * 100 * add_buff_rate), 10000);
            } else {
                Float vo = context.skillParams.get(add_buff_rate_var);
                if (vo != null) {
                    hit = CommonUtil.hit(RND, (int)(multiple * 100 * (vo.floatValue() + add_buff_rate)), 10000);
                }
            }
            if (hit) {
                context.source.buffs.addBuff(BuffUtil.createBuff(add_buff_id, add_buff_level, context.source, context.source, context.damage));
                effectTimes++;
            }
        }
    }

}
