package peony.game.buff;

import java.util.*;
import peony.game.*;
import peony.game.buff.*;
import peony.game.skill.*;
import peony.util.*;
import com.pip.util.*;
import org.apache.mina.common.ByteBuffer;
import peony.game.itemenhance.ItemEnhance;

public class AutoGeneratedBuff_420 implements Buff, PropertyEnhancer {
    private static final int[] WEAPON = {
        
    };
    public int buffover_addbuff = 0;
    public int buffover_addbuff_level = 0;
    public static int[] DURATION = {
        0, -1, -1
    };
    public static float[] ADD_NATUAL_PERCENT = {
        0.0f, 3.0f, 4.0f
    };
    public static float[] ADD_JEWEL_PERCENT = {
        0.0f, 3.0f, 4.0f
    };
    public static float[] ADD_STAR_PERCENT = {
        0.0f, 3.0f, 4.0f
    };
    int instanceID;
    int realWeight;
    int level;
    int endTime;
    int multiple;
    int remainSeconds;
    int tickInterval;
    int remainCure;
    int remainDamage;
    int remainMPCure;
    int remainMPDamage;
    int remainAbsorb;
    int effectTimes;
    GameObjectRef owner;
    GameObjectRef source;
    float add_natual_percent;
    float add_jewel_percent;
    float add_star_percent;


    public AutoGeneratedBuff_420(int lvl) {
        int dmg = 0;
        instanceID = BuffUtil.getNextID();
        level = lvl;
        multiple = 1;
        add_natual_percent = ADD_NATUAL_PERCENT[level];
        add_jewel_percent = ADD_JEWEL_PERCENT[level];
        add_star_percent = ADD_STAR_PERCENT[level];
    }

    public int getId() {
        return 420;
    }

    public int getInstanceID() {
        return instanceID;
    }

    public String getName() {
        return "8周年BUFF";
    }

    public String getDesc() {
        return java.text.MessageFormat.format("提高资质、宝石、星级各加幅度{0}", CommonUtil.formatPercent(add_natual_percent * multiple));
    }

    private boolean checkWeapon(Unit unit) {
        return true;
    }

    public int getEndTime() {
        return -1;
    }

    public boolean isGood() {
        return true;
    }

    public boolean dispelable() {
        return false;
    }

    public boolean keepOnDie() {
        return true;
    }

    public int getIconID() {
        return -1;
    }

    public boolean isAreaBuff() {
        return false;
    }

    public int getMergeStrategy() {
        return 2;
    }

    public boolean isNeedMerge() {
        return true;
    }

    public float getchange_dembuff_rate() {
         return 0;
    }

    public boolean merge(Buff buff) {
        if (buff instanceof AutoGeneratedBuff_420) {
            AutoGeneratedBuff_420 other = (AutoGeneratedBuff_420)buff;
            if (level <= other.level) {
                level = other.level;
                endTime = other.endTime;
                multiple = 1;
                remainSeconds = other.remainSeconds;
                tickInterval = other.tickInterval;
                remainCure = other.remainCure;
                remainDamage = other.remainDamage;
                remainMPCure = other.remainMPCure;
                remainMPDamage = other.remainMPDamage;
                remainAbsorb = other.remainAbsorb;
                effectTimes = 0;
                owner = other.owner;
                source = other.source;
                add_natual_percent = other.add_natual_percent;
                add_jewel_percent = other.add_jewel_percent;
                add_star_percent = other.add_star_percent;
            }
            return true;
        }
        return false;
    }

    public GameObjectRef getSource() {
        return source;
    }

    public void setOwner(GameObjectRef o) {
        owner = o;
        if (source == null) {
            source = owner;
        }
    }

    public void resetParams(Unit owner) {
        add_natual_percent = ADD_NATUAL_PERCENT[level];
        add_natual_percent = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 420, "add_natual_percent", add_natual_percent);
        add_jewel_percent = ADD_JEWEL_PERCENT[level];
        add_jewel_percent = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 420, "add_jewel_percent", add_jewel_percent);
        add_star_percent = ADD_STAR_PERCENT[level];
        add_star_percent = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 420, "add_star_percent", add_star_percent);
    }

    public void enhance(PropertyCalculator pc) {
        if (!checkWeapon(pc.unit)) {
            return;
        }
        if (add_natual_percent > 0.0f) {
            pc.natualEnhance = (multiple * add_natual_percent / 100.0f);
        }
        if (add_jewel_percent > 0.0f) {
            pc.jewelEnhance = (multiple * add_jewel_percent / 100.0f);
        }
        if (add_star_percent > 0.0f) {
            ItemEnhance.starCoefficient = (multiple * add_star_percent / 100.0f);
        }
    }

}
