    public boolean merge(Buff buff) {
        if (buff instanceof AutoGeneratedBuff_097) {
            AutoGeneratedBuff_097 other = (AutoGeneratedBuff_097)buff;
            if (level <= other.level) {
                level = other.level;
                endTime = other.endTime;
                multiple = 1;
                remainSeconds = other.remainSeconds;
                tickInterval = other.tickInterval;
                remainCure = other.remainCure;
                remainDamage = other.remainDamage;
                remainMPCure = other.remainMPCure;
                remainMPDamage = other.remainMPDamage;
                remainAbsorb = other.remainAbsorb;
                effectTimes = 0;
                owner = other.owner;
                source = other.source;
                limit_skills = other.limit_skills;
                change_b_magic_ap_value = other.change_b_magic_ap_value;
                change_b_magic_ap_percent = other.change_b_magic_ap_percent;
            }
            return true;
        }
        return false;
    }

    public GameObjectRef getSource() {
        return source;
    }

    public void setOwner(GameObjectRef o) {
        owner = o;
        if (source == null) {
            source = owner;
        }
    }

    public void resetParams(Unit owner) {
        change_b_magic_ap_value = CHANGE_B_MAGIC_AP_VALUE[level];
        change_b_magic_ap_value = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 97, "change_b_magic_ap_value", change_b_magic_ap_value);
        change_b_magic_ap_percent = CHANGE_B_MAGIC_AP_PERCENT[level];
        change_b_magic_ap_percent = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 97, "change_b_magic_ap_percent", change_b_magic_ap_percent);
    }

    public void preHit(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
        if (!limitSkills.contains(context.skill.getGroupId())) {
            return;
        }
    }

    public void postHit(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
        if (!limitSkills.contains(context.skill.getGroupId())) {
            return;
        }
    }

    public void preDamage(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
        if (!limitSkills.contains(context.skill.getGroupId())) {
            return;
        }
        if (isActive && (context.damageType == CombatContext.DAMAGE_MAGIC || context.damageType == CombatContext.DAMAGE_DECMP)) {
            context.attackPower += change_b_magic_ap_value;
            context.attackPowerRate += change_b_magic_ap_percent / 100.0f;
            effectTimes++;
        }
    }

    public void postDamage(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
        if (!limitSkills.contains(context.skill.getGroupId())) {
            return;
        }
    }

    public void finished(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
        if (!limitSkills.contains(context.skill.getGroupId())) {
            return;
        }
    }

