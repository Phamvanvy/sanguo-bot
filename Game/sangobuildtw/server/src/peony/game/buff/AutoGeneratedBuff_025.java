    public void resetParams(Unit owner) {
        add_debuff_rate = ADD_DEBUFF_RATE[level];
        add_debuff_rate = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 25, "add_debuff_rate", add_debuff_rate);
        add_debuff_level = ADD_DEBUFF_LEVEL[level];
        add_debuff_level = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 25, "add_debuff_level", add_debuff_level);
        slow_rate = SLOW_RATE[level];
        slow_rate = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 25, "slow_rate", slow_rate);
        slow_level = SLOW_LEVEL[level];
        slow_level = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 25, "slow_level", slow_level);
        slow_time = SLOW_TIME[level];
        slow_time = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 25, "slow_time", slow_time);
    }

