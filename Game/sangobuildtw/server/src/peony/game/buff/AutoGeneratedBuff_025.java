    public void finished(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
        if (isActive && context.hited() && context.isAttack()) {
            boolean hit = false;
            if (add_debuff_rate_var.length() == 0) {
                hit = CommonUtil.hit(RND, (int)(multiple * 100 * add_debuff_rate), 10000);
            } else {
                Float vo = context.skillParams.get(add_debuff_rate_var);
                if (vo != null) {
                    hit = CommonUtil.hit(RND, (int)(multiple * 100 * (vo.floatValue() + add_debuff_rate)), 10000);
                }
            }
            if (hit) {
                context.target.buffs.addBuff(BuffUtil.createBuff(add_debuff_id, add_debuff_level, context.source, context.target, context.damage));
                effectTimes++;
            }
        }
        if (isActive && context.hited() && context.isDamage()) {
            boolean hit = false;
            if (slow_rate_var.length() == 0) {
                hit = CommonUtil.hit(RND, (int)(multiple * 100 * slow_rate), 10000);
            } else {
                Float vo = context.skillParams.get(slow_rate_var);
                if (vo != null) {
                    hit = CommonUtil.hit(RND, (int)(multiple * 100 * (vo.floatValue() + slow_rate)), 10000);
                }
            }
            if (hit) {
                int sl = slow_level;
                Float vo = context.skillParams.get(slow_level_var);
                if (vo != null) {
                    sl += vo.intValue();
                }
                int tm = slow_time;
                vo = context.skillParams.get(slow_time_var);
                if (vo != null) {
                    tm *= 1.0f + vo.floatValue() / 100.0f;
                }
                context.activeSkills.add(new SlowSkill(sl, tm));
                effectTimes++;
            }
        }
    }

