package peony.game.buff;

import java.util.*;
import peony.game.*;
import peony.game.buff.*;
import peony.game.skill.*;
import peony.util.*;
import com.pip.util.*;
import org.apache.mina.common.ByteBuffer;

public class AutoGeneratedBuff_133 implements Buff, PropertyEnhancer, Updatable {
    private static final int[] WEAPON = {
        
    };
    public static int[] DURATION = {
        0, 3600000, 3600000
    };
    public static int[] CHANGE_AGI_VALUE = {
        0, 10, 30
    };
    public static float[] CHANGE_AGI_RATE = {
        0.0f, 0.0f, 0.0f
    };
    int instanceID;
    int level;
    int endTime;
    int multiple;
    int remainSeconds;
    int tickInterval;
    int remainCure;
    int remainDamage;
    int remainMPCure;
    int remainMPDamage;
    int remainAbsorb;
    int effectTimes;
    GameObjectRef owner;
    GameObjectRef source;
    int change_agi_value;
    float change_agi_rate;

    public AutoGeneratedBuff_133(int lvl, Unit src, Unit tgt, int dmg) {
        if (src != null) {
            source = src.ref();
        }
        if (tgt != null) {
            owner = tgt.ref();
        }
        instanceID = BuffUtil.getNextID();
        level = lvl;
        endTime = Time.currTime + BuffUtil.enhanceParam(src, tgt, 133, "buffTime", DURATION[level]);
        multiple = 1;
        change_agi_value = CHANGE_AGI_VALUE[level];
        change_agi_value = BuffUtil.enhanceParam(src, tgt, 133, "change_agi_value", change_agi_value);
        change_agi_rate = CHANGE_AGI_RATE[level];
        change_agi_rate = BuffUtil.enhanceParam(src, tgt, 133, "change_agi_rate", change_agi_rate);
    }

    public int getId() {
        return 133;
    }

    public int getInstanceID() {
        return instanceID;
    }

    public String getName() {
        return "敏捷增加";
    }

    public String getDesc() {
        return java.text.MessageFormat.format("敏捷提高{0}點", CommonUtil.formatValue(change_agi_value * multiple));
    }

    private boolean checkWeapon(Unit unit) {
        return true;
    }

    public int getEndTime() {
        return endTime;
    }

    public boolean isGood() {
        return false;
    }

    public boolean dispelable() {
        return true;
    }

    public boolean keepOnDie() {
        return true;
    }

    public int getIconID() {
        return 74 | 0x1000000;
    }

    public boolean isAreaBuff() {
        return false;
    }

    public boolean isNeedMerge() {
        return true;
    }

    public boolean merge(Buff buff) {
        if (buff instanceof AutoGeneratedBuff_133) {
            AutoGeneratedBuff_133 other = (AutoGeneratedBuff_133)buff;
            if (level <= other.level) {
                level = other.level;
                endTime = other.endTime;
                multiple = 1;
                remainSeconds = other.remainSeconds;
                tickInterval = other.tickInterval;
                remainCure = other.remainCure;
                remainDamage = other.remainDamage;
                remainMPCure = other.remainMPCure;
                remainMPDamage = other.remainMPDamage;
                remainAbsorb = other.remainAbsorb;
                effectTimes = 0;
                owner = other.owner;
                source = other.source;
                change_agi_value = other.change_agi_value;
                change_agi_rate = other.change_agi_rate;
            }
            return true;
        }
        return false;
    }

    public GameObjectRef getSource() {
        return source;
    }

    public void setOwner(GameObjectRef o) {
        owner = o;
        if (source == null) {
            source = owner;
        }
    }

    public void resetParams(Unit owner) {
    }

    public boolean update(int diff) {
        if (endTime <= Time.currTime) {
            return true;
        }
        return false;
    }

    public void load(byte[] bytes) {
        ByteBuffer buf = ByteBuffer.wrap(bytes);
        owner = new GameObjectRef(buf.get(), buf.getInt(), buf.getInt());
        source = new GameObjectRef(buf.get(), buf.getInt(), buf.getInt());
        level = buf.getInt();
        endTime = Time.elapseTime(buf.getLong());
        multiple = buf.getInt();
        change_agi_value = CHANGE_AGI_VALUE[level];
        change_agi_rate = CHANGE_AGI_RATE[level];
        remainSeconds = buf.getInt();
        tickInterval = buf.getInt();
        remainCure = buf.getInt();
        remainDamage = buf.getInt();
        remainMPCure = buf.getInt();
        remainMPDamage = buf.getInt();
        remainAbsorb = buf.getInt();
        effectTimes = buf.getInt();
    }

    public byte[] save() {
        ByteBuffer buf = ByteBuffer.allocate(66, false);
        buf.put(owner.type);
        buf.putInt(owner.id);
        buf.putInt(owner.instanceId);
        buf.put(source.type);
        buf.putInt(source.id);
        buf.putInt(source.instanceId);
        buf.putInt(level);
        buf.putLong(Time.currentTimeMillis(endTime));
        buf.putInt(multiple);
        buf.putInt(remainSeconds);
        buf.putInt(tickInterval);
        buf.putInt(remainCure);
        buf.putInt(remainDamage);
        buf.putInt(remainMPCure);
        buf.putInt(remainMPDamage);
        buf.putInt(remainAbsorb);
        buf.putInt(effectTimes);
        return buf.array();
    }

    public boolean update2(int time) {
        if (endTime <= Time.currTime) {
            return false;
        }
        return true;
    }

    public void enhance(PropertyCalculator pc) {
        if (!checkWeapon(pc.unit)) {
            return;
        }
        pc.agility *= 1.0f + multiple * change_agi_rate / 100.0f;
        pc.agility += multiple * change_agi_value;
    }

}
