package peony.game.buff;

import java.util.*;
import peony.game.*;
import peony.game.buff.*;
import peony.game.skill.*;
import peony.util.*;
import com.pip.util.*;
import org.apache.mina.common.ByteBuffer;

public class AutoGeneratedBuff_196 implements Buff, PropertyEnhancer, Updatable {
    private static final int[] WEAPON = {
        
    };
    public static int[] DURATION = {
        0, 8000, 10000, 15000, 20000
    };
    public static float[] CHANGE_MAGIC_HIT = {
        0.0f, -8.0f, -12.0f, -25.0f, -50.0f
    };
    public static float[] CHANGE_PHYSICAL_HIT = {
        0.0f, -8.0f, -12.0f, -25.0f, -50.0f
    };
    int instanceID;
    int level;
    int endTime;
    int multiple;
    int remainSeconds;
    int tickInterval;
    int remainCure;
    int remainDamage;
    int remainMPCure;
    int remainMPDamage;
    int remainAbsorb;
    int effectTimes;
    GameObjectRef owner;
    GameObjectRef source;
    float change_magic_hit;
    float change_physical_hit;

    public AutoGeneratedBuff_196(int lvl, Unit src, Unit tgt, int dmg) {
        if (src != null) {
            source = src.ref();
        }
        if (tgt != null) {
            owner = tgt.ref();
        }
        instanceID = BuffUtil.getNextID();
        level = lvl;
        endTime = Time.currTime + BuffUtil.enhanceParam(src, tgt, 196, "buffTime", DURATION[level]);
        multiple = 1;
        change_magic_hit = CHANGE_MAGIC_HIT[level];
        change_magic_hit = BuffUtil.enhanceParam(src, tgt, 196, "change_magic_hit", change_magic_hit);
        change_physical_hit = CHANGE_PHYSICAL_HIT[level];
        change_physical_hit = BuffUtil.enhanceParam(src, tgt, 196, "change_physical_hit", change_physical_hit);
    }

    public int getId() {
        return 196;
    }

    public int getInstanceID() {
        return instanceID;
    }

    public String getName() {
        return "命中降低";
    }

    public String getDesc() {
        return java.text.MessageFormat.format("降低{0}命中率", CommonUtil.formatPercent(change_magic_hit * multiple));
    }

    private boolean checkWeapon(Unit unit) {
        return true;
    }

    public int getEndTime() {
        return endTime;
    }

    public boolean isGood() {
        return false;
    }

    public boolean dispelable() {
        return false;
    }

    public boolean keepOnDie() {
        return false;
    }

    public int getIconID() {
        return 73 | 0x1000000;
    }

    public boolean isAreaBuff() {
        return false;
    }

    public boolean isNeedMerge() {
        return true;
    }

    public boolean merge(Buff buff) {
        if (buff instanceof AutoGeneratedBuff_196) {
            AutoGeneratedBuff_196 other = (AutoGeneratedBuff_196)buff;
            if (source.equals(other.source)) {
                level = other.level;
                endTime = other.endTime;
                multiple = 1;
                remainSeconds = other.remainSeconds;
                tickInterval = other.tickInterval;
                remainCure += other.remainCure;
                remainDamage += other.remainDamage;
                remainMPCure += other.remainMPCure;
                remainMPDamage += other.remainMPDamage;
                remainAbsorb = other.remainAbsorb;
                change_magic_hit = other.change_magic_hit;
                change_physical_hit = other.change_physical_hit;
                return true;
            }
        }
        return false;
    }

    public GameObjectRef getSource() {
        return source;
    }

    public void setOwner(GameObjectRef o) {
        owner = o;
        if (source == null) {
            source = owner;
        }
    }

    public void resetParams(Unit owner) {
    }

    public boolean update(int diff) {
        if (endTime <= Time.currTime) {
            return true;
        }
        return false;
    }

    public void load(byte[] bytes) {
        ByteBuffer buf = ByteBuffer.wrap(bytes);
        owner = new GameObjectRef(buf.get(), buf.getInt(), buf.getInt());
        source = new GameObjectRef(buf.get(), buf.getInt(), buf.getInt());
        level = buf.getInt();
        endTime = Time.elapseTime(buf.getLong());
        multiple = buf.getInt();
        change_magic_hit = CHANGE_MAGIC_HIT[level];
        change_physical_hit = CHANGE_PHYSICAL_HIT[level];
        remainSeconds = buf.getInt();
        tickInterval = buf.getInt();
        remainCure = buf.getInt();
        remainDamage = buf.getInt();
        remainMPCure = buf.getInt();
        remainMPDamage = buf.getInt();
        remainAbsorb = buf.getInt();
        effectTimes = buf.getInt();
    }

    public byte[] save() {
        ByteBuffer buf = ByteBuffer.allocate(66, false);
        buf.put(owner.type);
        buf.putInt(owner.id);
        buf.putInt(owner.instanceId);
        buf.put(source.type);
        buf.putInt(source.id);
        buf.putInt(source.instanceId);
        buf.putInt(level);
        buf.putLong(Time.currentTimeMillis(endTime));
        buf.putInt(multiple);
        buf.putInt(remainSeconds);
        buf.putInt(tickInterval);
        buf.putInt(remainCure);
        buf.putInt(remainDamage);
        buf.putInt(remainMPCure);
        buf.putInt(remainMPDamage);
        buf.putInt(remainAbsorb);
        buf.putInt(effectTimes);
        return buf.array();
    }

    public boolean update2(int time) {
        endTime += time;
        if (endTime <= Time.currTime) {
            return false;
        }
        return true;
    }

    public void enhance(PropertyCalculator pc) {
        if (!checkWeapon(pc.unit)) {
            return;
        }
        pc.spellhit += multiple * change_magic_hit / 100.0f;
        pc.hit += multiple * change_physical_hit / 100.0f;
    }

}
