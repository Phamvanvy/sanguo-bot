public class AutoGeneratedBuff_082 implements Buff, SkillBuff, CombatEffect {
    private static final int[] WEAPON = {
        
    };
    public static int[] DURATION = {
        0, -1
    };
    public static float[] BOUNCE_RATE = {
        0.0f, 5.0f
    };
    public static int[] BOUNCE_DAMAGE_TYPE = {
        0, 0
    };
    public static int[] BOUNCE_VALUE = {
        0, 0
    };
    public static float[] BOUNCE_PERCENT_OF_DAMAGE = {
        0.0f, 60.0f
    };
    Skill skill;
    int instanceID;
    int level;
    int endTime;
    int multiple;
    int remainSeconds;
    int tickInterval;
    int remainCure;
    int remainDamage;
    int remainMPCure;
    int remainMPDamage;
    int remainAbsorb;
    int effectTimes;
    GameObjectRef owner;
    GameObjectRef source;
    float bounce_rate;
    int bounce_damage_type;
    int bounce_value;
    float bounce_percent_of_damage;

    public AutoGeneratedBuff_082(Skill skl, int lvl) {
        int dmg = 0;
        skill = skl;
        instanceID = BuffUtil.getNextID();
        level = lvl;
        multiple = 1;
        bounce_rate = BOUNCE_RATE[level];
        bounce_damage_type = BOUNCE_DAMAGE_TYPE[level];
        bounce_value = BOUNCE_VALUE[level];
        bounce_percent_of_damage = BOUNCE_PERCENT_OF_DAMAGE[level];
    }

    public int getId() {
        return skill.getId();
    }

    public int getInstanceID() {
        return instanceID;
    }

    public String getName() {
        return "霸震";
    }

    public String getDesc() {
        return "有5%概率反彈受到傷害的60%";
    }

    public Skill getSkill() {
        return skill;
    }

    private boolean checkWeapon(Unit unit) {
        return true;
    }

    public int getEndTime() {
        return -1;
    }

    public boolean isGood() {
        return true;
    }

    public boolean dispelable() {
        return false;
    }

    public boolean keepOnDie() {
        return false;
    }

    public int getIconID() {
        return -1;
    }

    public boolean isAreaBuff() {
        return false;
    }

    public boolean isNeedMerge() {
        return true;
    }

    public boolean merge(Buff buff) {
        if (buff instanceof AutoGeneratedBuff_082) {
            AutoGeneratedBuff_082 other = (AutoGeneratedBuff_082)buff;
            if (level <= other.level) {
                level = other.level;
                endTime = other.endTime;
                multiple = 1;
                remainSeconds = other.remainSeconds;
                tickInterval = other.tickInterval;
                remainCure = other.remainCure;
                remainDamage = other.remainDamage;
                remainMPCure = other.remainMPCure;
                remainMPDamage = other.remainMPDamage;
                remainAbsorb = other.remainAbsorb;
                effectTimes = 0;
                owner = other.owner;
                source = other.source;
                bounce_rate = other.bounce_rate;
                bounce_damage_type = other.bounce_damage_type;
                bounce_value = other.bounce_value;
                bounce_percent_of_damage = other.bounce_percent_of_damage;
            }
            return true;
        }
        return false;
    }

    public GameObjectRef getSource() {
        return source;
    }

    public void setOwner(GameObjectRef o) {
        owner = o;
        if (source == null) {
            source = owner;
        }
    }

    public void resetParams(Unit owner) {
        bounce_rate = BOUNCE_RATE[level];
        bounce_rate = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 82, "bounce_rate", bounce_rate);
        bounce_damage_type = BOUNCE_DAMAGE_TYPE[level];
        bounce_damage_type = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 82, "bounce_damage_type", bounce_damage_type);
        bounce_value = BOUNCE_VALUE[level];
        bounce_value = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 82, "bounce_value", bounce_value);
        bounce_percent_of_damage = BOUNCE_PERCENT_OF_DAMAGE[level];
        bounce_percent_of_damage = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 82, "bounce_percent_of_damage", bounce_percent_of_damage);
    }

    public void preHit(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
    }

    public void postHit(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
    }

    public void preDamage(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
    }

    public void postDamage(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
    }

    public void finished(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
        if (!isActive && context.hited() && context.isDamage()) {
            if (CommonUtil.hit(RND, (int)(multiple * 100 * bounce_rate), 10000)) {
                int dmg = bounce_value;
                dmg += context.damage * bounce_percent_of_damage / 100.0f;
                context.passiveSkills.add(new FixedDamageSkill(bounce_damage_type, dmg));
                effectTimes++;
            }
        }
    }

}
