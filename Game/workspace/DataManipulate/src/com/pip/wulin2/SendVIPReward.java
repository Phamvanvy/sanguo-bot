	private static Object[] getAccountMaxRole(int accountID) throws Exception {
		String sql = "select id, playername, level, lastlogintime from tbl_userdata where accountid = " + accountID + 
			" and valid = 1 order by level desc, lastlogintime desc limit 1";
		int region = 1, id = 0, level = -1;
		String name = null;
		Date lastLoginTime = null;
		ArrayList<ResultRow> rs = DBUtils.query("wulin2_1", sql);
		if (rs != null && rs.size() > 0) {
			ResultRow row = rs.get(0);
			region = 1;
			id = row.getInt(1);
			name = row.getString(2);
			level = row.getInt(3);
			lastLoginTime = row.getDate(4);
		}
		rs = DBUtils.query("wulin2_2", sql);
		if (rs != null && rs.size() > 0) {
			ResultRow row = rs.get(0);
			int level2 = row.getInt(3);
			Date lastLoginTime2 = row.getDate(4);
			if (level2 > level || (level2 == level && lastLoginTime2.compareTo(lastLoginTime) > 0)) {
				region = 2;
				id = row.getInt(1);
				name = row.getString(2);
				level = level2;
				lastLoginTime = lastLoginTime2;
			}
		}
		if (lastLoginTime == null) {
			throw new Exception("帐号" + accountID + "没有角色");
		} else {
			System.out.println("选定" + region + "区角色 " + name + "(" + id + ") " + level + "级");
			return new Object[] { region, id, name };
		}
	}
