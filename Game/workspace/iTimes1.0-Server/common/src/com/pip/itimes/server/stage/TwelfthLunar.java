package com.pip.itimes.server.stage;

public class TwelfthLunar {
	/**
	 * 次数
	 */
	private int count;
	/**
	 * 礼物ID;
	 */
	private int giftId;
	/**
	 * 等级
	 */
	private int level;
	
	public void setCount (int count) {
		this.count = count;
	}
	public int getCount () {
		return count;
	}
	
	public void setGiftId (int giftId) {
		this.giftId = giftId;
	}
	public int getGiftId () {
		return giftId;
	}
	
	public void setLevel (int level) {
		this.level = level;
	}
	public int getLevel () {
		return level;
	}
}
