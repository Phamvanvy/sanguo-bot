public class AutoGeneratedBuff_216 implements Buff, PropertyEnhancer {
    private static final int[] WEAPON = {
        
    };
    public static int[] DURATION = {
        0, -1
    };
    public static int[] CHANGE_MAXHP_VALUE = {
        0, 0
    };
    public static float[] CHANGE_MAXHP_PERCENT = {
        0.0f, 5.0f
    };
    int instanceID;
    int level;
    int endTime;
    int multiple;
    int remainSeconds;
    int tickInterval;
    int remainCure;
    int remainDamage;
    int remainMPCure;
    int remainMPDamage;
    int remainAbsorb;
    int effectTimes;
    GameObjectRef owner;
    GameObjectRef source;
    int change_maxhp_value;
    float change_maxhp_percent;

    public AutoGeneratedBuff_216(int lvl) {
        int dmg = 0;
        instanceID = BuffUtil.getNextID();
        level = lvl;
        multiple = 1;
        change_maxhp_value = CHANGE_MAXHP_VALUE[level];
        change_maxhp_percent = CHANGE_MAXHP_PERCENT[level];
    }

    public int getId() {
        return 216;
    }

    public int getInstanceID() {
        return instanceID;
    }

    public String getName() {
        return "国公威武";
    }

    public String getDesc() {
        return "国公生命值上限提高5%";
    }

    private boolean checkWeapon(Unit unit) {
        return true;
    }

    public int getEndTime() {
        return -1;
    }

    public boolean isGood() {
        return true;
    }

    public boolean dispelable() {
        return false;
    }

    public boolean keepOnDie() {
        return false;
    }

    public int getIconID() {
        return -1;
    }

    public boolean isAreaBuff() {
        return false;
    }

    public boolean isNeedMerge() {
        return true;
    }

    public boolean merge(Buff buff) {
        if (buff instanceof AutoGeneratedBuff_216) {
            AutoGeneratedBuff_216 other = (AutoGeneratedBuff_216)buff;
            if (level <= other.level) {
                level = other.level;
                endTime = other.endTime;
                multiple = 1;
                remainSeconds = other.remainSeconds;
                tickInterval = other.tickInterval;
                remainCure = other.remainCure;
                remainDamage = other.remainDamage;
                remainMPCure = other.remainMPCure;
                remainMPDamage = other.remainMPDamage;
                remainAbsorb = other.remainAbsorb;
                effectTimes = 0;
                owner = other.owner;
                source = other.source;
                change_maxhp_value = other.change_maxhp_value;
                change_maxhp_percent = other.change_maxhp_percent;
            }
            return true;
        }
        return false;
    }

    public GameObjectRef getSource() {
        return source;
    }

    public void setOwner(GameObjectRef o) {
        owner = o;
        if (source == null) {
            source = owner;
        }
    }

    public void resetParams(Unit owner) {
        change_maxhp_value = CHANGE_MAXHP_VALUE[level];
        change_maxhp_value = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 216, "change_maxhp_value", change_maxhp_value);
        change_maxhp_percent = CHANGE_MAXHP_PERCENT[level];
        change_maxhp_percent = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 216, "change_maxhp_percent", change_maxhp_percent);
    }

    public void enhance(PropertyCalculator pc) {
        if (!checkWeapon(pc.unit)) {
            return;
        }
        pc.hp += multiple * change_maxhp_value;
        pc.hpRate += multiple * change_maxhp_percent / 100.0f;
    }

}
