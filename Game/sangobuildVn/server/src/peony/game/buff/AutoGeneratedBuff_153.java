package peony.game.buff;

import java.util.*;
import peony.game.*;
import peony.game.buff.*;
import peony.game.skill.*;
import peony.util.*;
import com.pip.util.*;
import org.apache.mina.common.ByteBuffer;
import peony.game.itemenhance.ItemEnhance;

public class AutoGeneratedBuff_153 implements Buff, Updatable, CombatEffect {
    private static final int[] WEAPON = {
        
    };
    public static int[] DURATION = {
        0, 20000, 20000
    };
    public static float[] BOUNCE_RATE = {
        0.0f, 100.0f, 100.0f
    };
    public static int[] BOUNCE_DAMAGE_TYPE = {
        0, 1, 1
    };
    public static int[] BOUNCE_VALUE = {
        0, 0, 0
    };
    public static float[] BOUNCE_PERCENT_OF_DAMAGE = {
        0.0f, 60.0f, 80.0f
    };
    int instanceID;
    int level;
    int endTime;
    int multiple;
    int remainSeconds;
    int tickInterval;
    int remainCure;
    int remainDamage;
    int remainMPCure;
    int remainMPDamage;
    int remainAbsorb;
    int effectTimes;
    GameObjectRef owner;
    GameObjectRef source;
    float bounce_rate;
    int bounce_damage_type;
    int bounce_value;
    float bounce_percent_of_damage;

    public AutoGeneratedBuff_153(int lvl, Unit src, Unit tgt, int dmg) {
        if (src != null) {
            source = src.ref();
        }
        if (tgt != null) {
            owner = tgt.ref();
        }
        instanceID = BuffUtil.getNextID();
        level = lvl;
        endTime = Time.currTime + BuffUtil.enhanceParam(src, tgt, 153, "buffTime", DURATION[level]);
        multiple = 1;
        bounce_rate = BOUNCE_RATE[level];
        bounce_rate = BuffUtil.enhanceParam(src, tgt, 153, "bounce_rate", bounce_rate);
        bounce_damage_type = BOUNCE_DAMAGE_TYPE[level];
        bounce_damage_type = BuffUtil.enhanceParam(src, tgt, 153, "bounce_damage_type", bounce_damage_type);
        bounce_value = BOUNCE_VALUE[level];
        bounce_value = BuffUtil.enhanceParam(src, tgt, 153, "bounce_value", bounce_value);
        bounce_percent_of_damage = BOUNCE_PERCENT_OF_DAMAGE[level];
        bounce_percent_of_damage = BuffUtil.enhanceParam(src, tgt, 153, "bounce_percent_of_damage", bounce_percent_of_damage);
    }

    public int getId() {
        return 153;
    }

    public int getInstanceID() {
        return instanceID;
    }

    public String getName() {
        return "反伤";
    }

    public String getDesc() {
        return "";
    }

    private boolean checkWeapon(Unit unit) {
        return true;
    }

    public int getEndTime() {
        return endTime;
    }

    public boolean isGood() {
        return true;
    }

    public boolean dispelable() {
        return true;
    }

    public boolean keepOnDie() {
        return false;
    }

    public int getIconID() {
        return -1;
    }

    public boolean isAreaBuff() {
        return false;
    }

    public boolean isNeedMerge() {
        return true;
    }

    public boolean merge(Buff buff) {
        if (buff instanceof AutoGeneratedBuff_153) {
            AutoGeneratedBuff_153 other = (AutoGeneratedBuff_153)buff;
            if (level <= other.level) {
                level = other.level;
                endTime = other.endTime;
                multiple = 1;
                remainSeconds = other.remainSeconds;
                tickInterval = other.tickInterval;
                remainCure = other.remainCure;
                remainDamage = other.remainDamage;
                remainMPCure = other.remainMPCure;
                remainMPDamage = other.remainMPDamage;
                remainAbsorb = other.remainAbsorb;
                effectTimes = 0;
                owner = other.owner;
                source = other.source;
                bounce_rate = other.bounce_rate;
                bounce_damage_type = other.bounce_damage_type;
                bounce_value = other.bounce_value;
                bounce_percent_of_damage = other.bounce_percent_of_damage;
            }
            return true;
        }
        return false;
    }

    public GameObjectRef getSource() {
        return source;
    }

    public void setOwner(GameObjectRef o) {
        owner = o;
        if (source == null) {
            source = owner;
        }
    }

    public void resetParams(Unit owner) {
    }

    public boolean update(int diff) {
        if (endTime <= Time.currTime) {
            return true;
        }
        return false;
    }

    public void load(byte[] bytes) {
        ByteBuffer buf = ByteBuffer.wrap(bytes);
        owner = new GameObjectRef(buf.get(), buf.getInt(), buf.getInt());
        source = new GameObjectRef(buf.get(), buf.getInt(), buf.getInt());
        level = buf.getInt();
        endTime = Time.elapseTime(buf.getLong());
        multiple = buf.getInt();
        bounce_rate = BOUNCE_RATE[level];
        bounce_damage_type = BOUNCE_DAMAGE_TYPE[level];
        bounce_value = BOUNCE_VALUE[level];
        bounce_percent_of_damage = BOUNCE_PERCENT_OF_DAMAGE[level];
        remainSeconds = buf.getInt();
        tickInterval = buf.getInt();
        remainCure = buf.getInt();
        remainDamage = buf.getInt();
        remainMPCure = buf.getInt();
        remainMPDamage = buf.getInt();
        remainAbsorb = buf.getInt();
        effectTimes = buf.getInt();
    }

    public byte[] save() {
        ByteBuffer buf = ByteBuffer.allocate(66, false);
        buf.put(owner.type);
        buf.putInt(owner.id);
        buf.putInt(owner.instanceId);
        buf.put(source.type);
        buf.putInt(source.id);
        buf.putInt(source.instanceId);
        buf.putInt(level);
        buf.putLong(Time.currentTimeMillis(endTime));
        buf.putInt(multiple);
        buf.putInt(remainSeconds);
        buf.putInt(tickInterval);
        buf.putInt(remainCure);
        buf.putInt(remainDamage);
        buf.putInt(remainMPCure);
        buf.putInt(remainMPDamage);
        buf.putInt(remainAbsorb);
        buf.putInt(effectTimes);
        return buf.array();
    }

    public boolean update2(int time) {
        endTime += time;
        if (endTime <= Time.currTime) {
            return false;
        }
        return true;
    }

    public void preHit(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
    }

    public void postHit(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
    }

    public void preDamage(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
    }

    public void postDamage(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
    }

    public void finished(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
        if (!isActive && context.hited() && context.isDamage()) {
            if (CommonUtil.hit(RND, (int)(multiple * 100 * bounce_rate), 10000)) {
                int dmg = bounce_value;
                dmg += context.damage * bounce_percent_of_damage / 100.0f;
                context.passiveSkills.add(new FixedDamageSkill(bounce_damage_type, dmg));
                effectTimes++;
            }
        }
    }

}
