package peony.game.buff;

import java.util.*;
import peony.game.*;
import peony.game.buff.*;
import peony.game.skill.*;
import peony.util.*;
import com.pip.util.*;
import org.apache.mina.common.ByteBuffer;
import peony.game.itemenhance.ItemEnhance;

public class AutoGeneratedBuff_345 implements Buff, PropertyEnhancer, Updatable {
    private static final int[] WEAPON = {
        
    };
    public static int[] DURATION = {
        0, 1800000
    };
    public static String[] LIMIT_MAP = {
        "", "978"
    };
    public static int[] CHANGE_ARMOR_VALUE = {
        0, 0
    };
    public static float[] CHANGE_ARMOR_PERCENT = {
        0.0f, 50.0f
    };
    public static int[] CHANGE_MAGIC_ARMOR_VALUE = {
        0, 0
    };
    public static float[] CHANGE_MAGIC_ARMOR_PERCENT = {
        0.0f, 50.0f
    };
    int instanceID;
    int level;
    int endTime;
    int multiple;
    int remainSeconds;
    int tickInterval;
    int remainCure;
    int remainDamage;
    int remainMPCure;
    int remainMPDamage;
    int remainAbsorb;
    int effectTimes;
    GameObjectRef owner;
    GameObjectRef source;
    IntHashSet limitMaps = new IntHashSet();
    String limit_map;
    int change_armor_value;
    float change_armor_percent;
    int change_magic_armor_value;
    float change_magic_armor_percent;

    public AutoGeneratedBuff_345(int lvl, Unit src, Unit tgt, int dmg) {
        if (src != null) {
            source = src.ref();
        }
        if (tgt != null) {
            owner = tgt.ref();
        }
        instanceID = BuffUtil.getNextID();
        level = lvl;
        endTime = Time.currTime + BuffUtil.enhanceParam(src, tgt, 345, "buffTime", DURATION[level]);
        multiple = 1;
        limit_map = LIMIT_MAP[level];
        change_armor_value = CHANGE_ARMOR_VALUE[level];
        change_armor_value = BuffUtil.enhanceParam(src, tgt, 345, "change_armor_value", change_armor_value);
        change_armor_percent = CHANGE_ARMOR_PERCENT[level];
        change_armor_percent = BuffUtil.enhanceParam(src, tgt, 345, "change_armor_percent", change_armor_percent);
        change_magic_armor_value = CHANGE_MAGIC_ARMOR_VALUE[level];
        change_magic_armor_value = BuffUtil.enhanceParam(src, tgt, 345, "change_magic_armor_value", change_magic_armor_value);
        change_magic_armor_percent = CHANGE_MAGIC_ARMOR_PERCENT[level];
        change_magic_armor_percent = BuffUtil.enhanceParam(src, tgt, 345, "change_magic_armor_percent", change_magic_armor_percent);
        String[] secs = limit_map.split(",");
        for (String s : secs) {
            limitMaps.add(Integer.parseInt(s));
        }
    }

    public int getId() {
        return 345;
    }

    public int getInstanceID() {
        return instanceID;
    }

    public String getName() {
        return "副本内防御提升（困难天龙）";
    }

    public String getDesc() {
        return java.text.MessageFormat.format("防御力提升了{0}", CommonUtil.formatPercent(change_armor_percent * multiple));
    }

    private boolean checkWeapon(Unit unit) {
        return true;
    }

    public int getEndTime() {
        return endTime;
    }

    public boolean isGood() {
        return true;
    }

    public boolean dispelable() {
        return false;
    }

    public boolean keepOnDie() {
        return true;
    }

    public int getIconID() {
        return 74 | 0x1000000;
    }

    public boolean isAreaBuff() {
        return false;
    }

    public boolean isNeedMerge() {
        return true;
    }

    public boolean merge(Buff buff) {
        if (buff instanceof AutoGeneratedBuff_345) {
            AutoGeneratedBuff_345 other = (AutoGeneratedBuff_345)buff;
            if (source.equals(other.source)) {
                level = other.level;
                endTime = other.endTime;
                multiple = 1;
                remainSeconds = other.remainSeconds;
                tickInterval = other.tickInterval;
                remainCure += other.remainCure;
                remainDamage += other.remainDamage;
                remainMPCure += other.remainMPCure;
                remainMPDamage += other.remainMPDamage;
                remainAbsorb = other.remainAbsorb;
                limit_map = other.limit_map;
                change_armor_value = other.change_armor_value;
                change_armor_percent = other.change_armor_percent;
                change_magic_armor_value = other.change_magic_armor_value;
                change_magic_armor_percent = other.change_magic_armor_percent;
                return true;
            }
        }
        return false;
    }

    public GameObjectRef getSource() {
        return source;
    }

    public void setOwner(GameObjectRef o) {
        owner = o;
        if (source == null) {
            source = owner;
        }
    }

    public void resetParams(Unit owner) {
    }

    public boolean update(int diff) {
        if (endTime <= Time.currTime) {
            return true;
        }
        return false;
    }

    public void load(byte[] bytes) {
        ByteBuffer buf = ByteBuffer.wrap(bytes);
        owner = new GameObjectRef(buf.get(), buf.getInt(), buf.getInt());
        source = new GameObjectRef(buf.get(), buf.getInt(), buf.getInt());
        level = buf.getInt();
        endTime = Time.elapseTime(buf.getLong());
        multiple = buf.getInt();
        limit_map = LIMIT_MAP[level];
        change_armor_value = CHANGE_ARMOR_VALUE[level];
        change_armor_percent = CHANGE_ARMOR_PERCENT[level];
        change_magic_armor_value = CHANGE_MAGIC_ARMOR_VALUE[level];
        change_magic_armor_percent = CHANGE_MAGIC_ARMOR_PERCENT[level];
        remainSeconds = buf.getInt();
        tickInterval = buf.getInt();
        remainCure = buf.getInt();
        remainDamage = buf.getInt();
        remainMPCure = buf.getInt();
        remainMPDamage = buf.getInt();
        remainAbsorb = buf.getInt();
        effectTimes = buf.getInt();
    }

    public byte[] save() {
        ByteBuffer buf = ByteBuffer.allocate(66, false);
        buf.put(owner.type);
        buf.putInt(owner.id);
        buf.putInt(owner.instanceId);
        buf.put(source.type);
        buf.putInt(source.id);
        buf.putInt(source.instanceId);
        buf.putInt(level);
        buf.putLong(Time.currentTimeMillis(endTime));
        buf.putInt(multiple);
        buf.putInt(remainSeconds);
        buf.putInt(tickInterval);
        buf.putInt(remainCure);
        buf.putInt(remainDamage);
        buf.putInt(remainMPCure);
        buf.putInt(remainMPDamage);
        buf.putInt(remainAbsorb);
        buf.putInt(effectTimes);
        return buf.array();
    }

    public boolean update2(int time) {
        if (endTime <= Time.currTime) {
            return false;
        }
        return true;
    }

    public void enhance(PropertyCalculator pc) {
        if (!checkWeapon(pc.unit)) {
            return;
        }
        if (owner != null) {
            GameObject ownerUnit = ObjectAccessor.getGameObject(owner);
            if (ownerUnit != null && !limitMaps.contains(ownerUnit.map.id)) {
                return;
            }
        }
        pc.defenseRate += multiple * change_armor_percent / 100.0f;
        pc.defense += multiple * change_armor_value;
        if (pc.defense < 0) {
            pc.defense = 0;
        }
        pc.spellDefenseRate += multiple * change_magic_armor_percent / 100.0f;
        pc.spelldefense += multiple * change_magic_armor_value;
        if (pc.spelldefense < 0) {
            pc.spelldefense = 0;
        }
    }

}
