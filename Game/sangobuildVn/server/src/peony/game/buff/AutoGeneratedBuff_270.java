package peony.game.buff;

import java.util.*;
import peony.game.*;
import peony.game.buff.*;
import peony.game.skill.*;
import peony.util.*;
import com.pip.util.*;
import org.apache.mina.common.ByteBuffer;
import peony.game.itemenhance.ItemEnhance;

public class AutoGeneratedBuff_270 implements Buff, PropertyEnhancer {
    private static final int[] WEAPON = {
        
    };
    public static int[] DURATION = {
        0, -1, -1, -1, -1, -1
    };
    public static float[] CHANGE_PHYSICAL_CRIT = {
        0.0f, 5.0f, 10.0f, 15.0f, 20.0f, 25.0f
    };
    public static float[] CHANGE_MAGIC_CRIT = {
        0.0f, 5.0f, 10.0f, 15.0f, 20.0f, 25.0f
    };
    int instanceID;
    int level;
    int endTime;
    int multiple;
    int remainSeconds;
    int tickInterval;
    int remainCure;
    int remainDamage;
    int remainMPCure;
    int remainMPDamage;
    int remainAbsorb;
    int effectTimes;
    GameObjectRef owner;
    GameObjectRef source;
    float change_physical_crit;
    float change_magic_crit;

    public AutoGeneratedBuff_270(int lvl) {
        int dmg = 0;
        instanceID = BuffUtil.getNextID();
        level = lvl;
        multiple = 1;
        change_physical_crit = CHANGE_PHYSICAL_CRIT[level];
        change_magic_crit = CHANGE_MAGIC_CRIT[level];
    }

    public int getId() {
        return 270;
    }

    public int getInstanceID() {
        return instanceID;
    }

    public String getName() {
        return "驸马的威严";
    }

    public String getDesc() {
        return java.text.MessageFormat.format("驸马爷不是吃素的，暴击率提升了{0}", CommonUtil.formatPercent(change_physical_crit * multiple));
    }

    private boolean checkWeapon(Unit unit) {
        return true;
    }

    public int getEndTime() {
        return -1;
    }

    public boolean isGood() {
        return true;
    }

    public boolean dispelable() {
        return false;
    }

    public boolean keepOnDie() {
        return true;
    }

    public int getIconID() {
        return -1;
    }

    public boolean isAreaBuff() {
        return false;
    }

    public boolean isNeedMerge() {
        return true;
    }

    public boolean merge(Buff buff) {
        if (buff instanceof AutoGeneratedBuff_270) {
            AutoGeneratedBuff_270 other = (AutoGeneratedBuff_270)buff;
            if (level <= other.level) {
                level = other.level;
                endTime = other.endTime;
                multiple = 1;
                remainSeconds = other.remainSeconds;
                tickInterval = other.tickInterval;
                remainCure = other.remainCure;
                remainDamage = other.remainDamage;
                remainMPCure = other.remainMPCure;
                remainMPDamage = other.remainMPDamage;
                remainAbsorb = other.remainAbsorb;
                effectTimes = 0;
                owner = other.owner;
                source = other.source;
                change_physical_crit = other.change_physical_crit;
                change_magic_crit = other.change_magic_crit;
            }
            return true;
        }
        return false;
    }

    public GameObjectRef getSource() {
        return source;
    }

    public void setOwner(GameObjectRef o) {
        owner = o;
        if (source == null) {
            source = owner;
        }
    }

    public void resetParams(Unit owner) {
        change_physical_crit = CHANGE_PHYSICAL_CRIT[level];
        change_physical_crit = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 270, "change_physical_crit", change_physical_crit);
        change_magic_crit = CHANGE_MAGIC_CRIT[level];
        change_magic_crit = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 270, "change_magic_crit", change_magic_crit);
    }

    public void enhance(PropertyCalculator pc) {
        if (!checkWeapon(pc.unit)) {
            return;
        }
        pc.critical += multiple * change_physical_crit / 100.0f;
        pc.spellcritical += multiple * change_magic_crit / 100.0f;
    }

}
