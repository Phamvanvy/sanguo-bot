    public void finished(CombatContext context, boolean isActive) {
        if (!checkWeapon(isActive ? context.source : context.target)) {
            return;
        }
        if (isActive && context.hited() && context.isDamage()) {
            boolean hit = false;
            if (paralyze_rate_var.length() == 0) {
                hit = CommonUtil.hit(RND, (int)(multiple * 100 * paralyze_rate), 10000);
            } else {
                Float vo = context.skillParams.get(paralyze_rate_var);
                if (vo != null) {
                    hit = CommonUtil.hit(RND, (int)(multiple * 100 * (vo.floatValue() + paralyze_rate)), 10000);
                }
            }
            if (hit) {
                context.activeSkills.add(new ParalyzeSkill(paralyse_time));
                effectTimes++;
            }
        }
    }

