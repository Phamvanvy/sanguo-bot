package peony.game.buff;

import java.util.*;
import peony.game.*;
import peony.game.buff.*;
import peony.game.skill.*;
import peony.util.*;
import com.pip.util.*;
import org.apache.mina.common.ByteBuffer;
import peony.game.itemenhance.ItemEnhance;

public class AutoGeneratedBuff_105 implements Buff, SkillBuff, PropertyEnhancer {
    private static final int[] WEAPON = {
        
    };
    public int buffover_addbuff = 0;
    public int buffover_addbuff_level = 0;
    public static int[] DURATION = {
        0, -1, -1, -1, -1, -1
    };
    public static int[] CHANGE_BASIC_HP_VALUE = {
        0, 0, 0, 0, 0, 0
    };
    public static float[] CHANGE_BASIC_HP_RATE = {
        0.0f, 5.0f, 6.0f, 7.0f, 8.0f, 9.0f
    };
    Skill skill;
    int instanceID;
    int level;
    int endTime;
    int multiple;
    int remainSeconds;
    int tickInterval;
    int remainCure;
    int remainDamage;
    int remainMPCure;
    int remainMPDamage;
    int remainAbsorb;
    int effectTimes;
    GameObjectRef owner;
    GameObjectRef source;
    int change_basic_hp_value;
    float change_basic_hp_rate;

    public AutoGeneratedBuff_105(Skill skl, int lvl) {
        int dmg = 0;
        skill = skl;
        instanceID = BuffUtil.getNextID();
        level = lvl;
        multiple = 1;
        change_basic_hp_value = CHANGE_BASIC_HP_VALUE[level];
        change_basic_hp_rate = CHANGE_BASIC_HP_RATE[level];
    }

    public int getId() {
        return skill.getId();
    }

    public int getInstanceID() {
        return instanceID;
    }

    public String getName() {
        return "仙气护体";
    }

    public String getDesc() {
        return java.text.MessageFormat.format("提升基础精力/气力上限{0}", CommonUtil.formatPercent(change_basic_hp_rate * multiple));
    }

    public Skill getSkill() {
        return skill;
    }

    private boolean checkWeapon(Unit unit) {
        return true;
    }

    public int getEndTime() {
        return -1;
    }

    public boolean isGood() {
        return true;
    }

    public boolean dispelable() {
        return false;
    }

    public boolean keepOnDie() {
        return false;
    }

    public int getIconID() {
        return -1;
    }

    public boolean isAreaBuff() {
        return false;
    }

    public boolean isNeedMerge() {
        return true;
    }

    public boolean merge(Buff buff) {
        if (buff instanceof AutoGeneratedBuff_105) {
            AutoGeneratedBuff_105 other = (AutoGeneratedBuff_105)buff;
            if (level <= other.level) {
                level = other.level;
                endTime = other.endTime;
                multiple = 1;
                remainSeconds = other.remainSeconds;
                tickInterval = other.tickInterval;
                remainCure = other.remainCure;
                remainDamage = other.remainDamage;
                remainMPCure = other.remainMPCure;
                remainMPDamage = other.remainMPDamage;
                remainAbsorb = other.remainAbsorb;
                effectTimes = 0;
                owner = other.owner;
                source = other.source;
                change_basic_hp_value = other.change_basic_hp_value;
                change_basic_hp_rate = other.change_basic_hp_rate;
            }
            return true;
        }
        return false;
    }

    public GameObjectRef getSource() {
        return source;
    }

    public void setOwner(GameObjectRef o) {
        owner = o;
        if (source == null) {
            source = owner;
        }
    }

    public void resetParams(Unit owner) {
        change_basic_hp_value = CHANGE_BASIC_HP_VALUE[level];
        change_basic_hp_value = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 105, "change_basic_hp_value", change_basic_hp_value);
        change_basic_hp_rate = CHANGE_BASIC_HP_RATE[level];
        change_basic_hp_rate = owner.buffs.getParamEnhances().enhance(ParamEnhanceSet.TYPE_BUFF_OWNER, 105, "change_basic_hp_rate", change_basic_hp_rate);
    }

    public void enhance(PropertyCalculator pc) {
        if (!checkWeapon(pc.unit)) {
            return;
        }
        pc.hp += multiple * change_basic_hp_value;
        pc.basicHpRate += multiple * change_basic_hp_rate / 100.0f;
    }

}
